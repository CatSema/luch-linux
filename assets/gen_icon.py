#!/usr/bin/env python3
"""Generates every Luch icon from one geometry: a laptop beams its picture up onto a 16:9 screen,
the beam drawn as light through dust. Outputs (paths relative to this file):

  luch.svg / luch.png            colour icon (README, F-Droid, banners)
  luch-symbolic.svg              16 px monochrome (GNOME panel)
  android/*.xml                  adaptive launcher layers + notification icon (copy into res/drawable)

Run: python3 gen_icon.py      SPDX-License-Identifier: GPL-3.0-or-later
"""
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
SL, SR, SY = 230, 282, 362      # beam at the laptop screen
TL, TR, TY = 120, 392, 90       # beam at the big screen (hidden behind it)
SCREEN = (120, 76, 272, 153, 18)   # x, y, w, h, r  (16:9)
INNER = (136, 92, 240, 121, 10)
LID = (198, 350, 116, 76, 10)
LID_GLASS = (207, 359, 98, 58, 5)
BASE = "M170 428 H342 L354 444 Q354 448 348 448 H164 Q158 448 158 444 Z"


def geometry(seed=11):
    rnd = random.Random(seed)
    edges = sorted(rnd.sample(range(1, 40), 13))
    pts = [0] + [e / 40 for e in edges] + [1]
    rays = []
    for i in range(0, len(pts) - 1, 2):  # every other slice: gaps like light through clouds
        a, b = pts[i], pts[i + 1]
        quad = [(SL + (SR - SL) * a, SY), (SL + (SR - SL) * b, SY),
                (TL + (TR - TL) * b, TY), (TL + (TR - TL) * a, TY)]
        rays.append((quad, 0.22 + rnd.random() * 0.33))

    def half_at(y):
        t = (SY - y) / (SY - TY)
        return (SR - SL) / 2 + t * ((TR - TL) / 2 - (SR - SL) / 2)

    dust = []
    for _ in range(22):
        y = rnd.uniform(236, SY - 14)
        x = 256 + rnd.uniform(-1, 1) * half_at(y) * 0.85
        dust.append((x, y, rnd.uniform(1.4, 3.6), rnd.uniform(0.35, 0.85)))
    return rays, dust


def rrect(x, y, w, h, r):
    return (f"M{x + r},{y}h{w - 2 * r}a{r},{r} 0,0 1,{r} {r}v{h - 2 * r}a{r},{r} 0,0 1,-{r} {r}"
            f"h-{w - 2 * r}a{r},{r} 0,0 1,-{r} -{r}v-{h - 2 * r}a{r},{r} 0,0 1,{r} -{r}z")


def poly(q):
    return "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in q) + "Z"


def circle(cx, cy, r):
    return f"M{cx - r:.1f},{cy:.1f}a{r:.1f},{r:.1f} 0,1 0,{2 * r:.1f} 0a{r:.1f},{r:.1f} 0,1 0,-{2 * r:.1f} 0z"


def svg_colour(rays, dust):
    cone = poly([(SL, SY), (SR, SY), (TR, TY), (TL, TY)])
    r = "".join(f'<path d="{poly(q)}" fill="url(#ray)" fill-opacity="{o:.2f}"/>' for q, o in rays)
    d = "".join(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{s:.1f}" fill="#FFF6DE" fill-opacity="{o:.2f}"/>' for x, y, s, o in dust)
    return f'''<!-- SPDX-License-Identifier: GPL-3.0-or-later -->
<!-- Luch: a laptop beams its picture up onto a 16:9 screen; the beam is light through dust. Generated by gen_icon.py. -->
<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#1A2340"/><stop offset="1" stop-color="#2B1742"/></linearGradient>
    <linearGradient id="cone" x1="0" y1="1" x2="0" y2="0"><stop offset="0" stop-color="#FFF4D6" stop-opacity="0.38"/><stop offset="1" stop-color="#FFB547" stop-opacity="0.08"/></linearGradient>
    <linearGradient id="ray" x1="0" y1="1" x2="0" y2="0"><stop offset="0" stop-color="#FFFBEF"/><stop offset="0.7" stop-color="#FFD58A" stop-opacity="0.55"/><stop offset="1" stop-color="#FFB547" stop-opacity="0.15"/></linearGradient>
    <linearGradient id="screen" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#FFE7A6"/><stop offset="1" stop-color="#FF8F3A"/></linearGradient>
    <radialGradient id="halo" cx="0.5" cy="0.5" r="0.5"><stop offset="0" stop-color="#FFD98A" stop-opacity="0.5"/><stop offset="1" stop-color="#FFD98A" stop-opacity="0"/></radialGradient>
    <filter id="soft" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="2.4"/></filter>
  </defs>
  <rect width="512" height="512" rx="112" fill="url(#bg)"/>
  <g filter="url(#soft)"><path d="{cone}" fill="url(#cone)"/>{r}</g>
  {d}
  <ellipse cx="256" cy="150" rx="186" ry="112" fill="url(#halo)"/>
  <path d="{rrect(*SCREEN)}" fill="url(#screen)"/>
  <path d="{rrect(*INNER)}" fill="#FFF6DC" fill-opacity="0.32"/>
  <path d="{rrect(*LID)}" fill="#E9EDF8"/>
  <path d="{rrect(*LID_GLASS)}" fill="#FFE7A6"/>
  <path d="{BASE}" fill="#E9EDF8"/>
</svg>
'''


SYMBOLIC = '''<!-- SPDX-License-Identifier: GPL-3.0-or-later -->
<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16">
  <path d="M7 11 L9 11 L13.5 6 L2.5 6 Z" fill="#222" fill-opacity="0.45"/>
  <rect x="1.5" y="1" width="13" height="7.3" rx="1.2" fill="#222"/>
  <rect x="5" y="10.5" width="6" height="3.4" rx="0.6" fill="#222"/>
  <rect x="3.5" y="14.2" width="9" height="1.3" rx="0.6" fill="#222"/>
</svg>
'''

# Content box (x 70..442, y 38..448) mapped into the 66 dp safe zone of a 108 dp adaptive icon.
SCALE, TX, TY_ = 0.177, 8.69, 7.63
AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'


def grad_linear(x0, y0, x1, y1, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="{x0}" '
            f'android:startY="{y0}" android:endX="{x1}" android:endY="{y1}">{items}</gradient></aapt:attr>')


def android_foreground(rays, dust):
    p = []
    p.append(f'<path android:pathData="{circle(256, 150, 186)}"><aapt:attr name="android:fillColor"><gradient android:type="radial" android:centerX="256" android:centerY="150" android:gradientRadius="186"><item android:offset="0" android:color="#66FFD98A" /><item android:offset="1" android:color="#00FFD98A" /></gradient></aapt:attr></path>')
    p.append(f'<path android:pathData="{poly([(SL, SY), (SR, SY), (TR, TY), (TL, TY)])}">{grad_linear(256, SY, 256, TY, [(0, "#61FFF4D6"), (1, "#14FFB547")])}</path>')
    for q, o in rays:  # no blur on Android: a touch more transparent
        p.append(f'<path android:fillAlpha="{o * 0.8:.2f}" android:pathData="{poly(q)}">{grad_linear(256, SY, 256, TY, [(0, "#FFFFFBEF"), (0.7, "#8CFFD58A"), (1, "#26FFB547")])}</path>')
    for x, y, s, o in dust:
        p.append(f'<path android:fillColor="#FFFFF6DE" android:fillAlpha="{o:.2f}" android:pathData="{circle(x, y, s)}" />')
    p.append(f'<path android:pathData="{rrect(*SCREEN)}">{grad_linear(120, 76, 392, 229, [(0, "#FFFFE7A6"), (1, "#FFFF8F3A")])}</path>')
    p.append(f'<path android:fillColor="#52FFF6DC" android:pathData="{rrect(*INNER)}" />')
    p.append(f'<path android:fillColor="#FFE9EDF8" android:pathData="{rrect(*LID)}" />')
    p.append(f'<path android:fillColor="#FFFFE7A6" android:pathData="{rrect(*LID_GLASS)}" />')
    p.append(f'<path android:fillColor="#FFE9EDF8" android:pathData="{BASE.replace(" ", ",").replace(",H", "H").replace(",L", "L").replace(",Q", "Q").replace(",Z", "Z")}" />')
    return vector(108, 108, "\n        ".join(p), group=True, aapt=True)


def android_monochrome():
    p = [f'<path android:fillColor="#FFFFFFFF" android:fillAlpha="0.45" android:pathData="{poly([(SL, SY), (SR, SY), (TR, TY), (TL, TY)])}" />',
         f'<path android:fillColor="#FFFFFFFF" android:pathData="{rrect(*SCREEN)}" />',
         f'<path android:fillColor="#FFFFFFFF" android:pathData="{rrect(*LID)}" />',
         f'<path android:fillColor="#FFFFFFFF" android:pathData="M170,428H342L354,444Q354,448 348,448H164Q158,448 158,444Z" />']
    return vector(108, 108, "\n        ".join(p), group=True)


def android_notification():
    p = ['<path android:fillColor="#FFFFFFFF" android:fillAlpha="0.5" android:pathData="M7,11L9,11L13.5,6L2.5,6Z" />',
         '<path android:fillColor="#FFFFFFFF" android:pathData="M2.7,1h10.6a1.2,1.2 0,0 1,1.2 1.2v4.9a1.2,1.2 0,0 1,-1.2 1.2h-10.6a1.2,1.2 0,0 1,-1.2 -1.2v-4.9a1.2,1.2 0,0 1,1.2 -1.2z" />',
         '<path android:fillColor="#FFFFFFFF" android:pathData="M5.6,10.5h4.8a0.6,0.6 0,0 1,0.6 0.6v2.2a0.6,0.6 0,0 1,-0.6 0.6h-4.8a0.6,0.6 0,0 1,-0.6 -0.6v-2.2a0.6,0.6 0,0 1,0.6 -0.6z" />',
         '<path android:fillColor="#FFFFFFFF" android:pathData="M4.1,14.2h7.8a0.6,0.6 0,0 1,0 1.3h-7.8a0.6,0.6 0,0 1,0 -1.3z" />']
    return vector(16, 16, "\n    ".join(p), size_dp=24)


def vector(vw, vh, body, group=False, aapt=False, size_dp=None):
    dp = size_dp or vw
    head = (f'<!-- SPDX-License-Identifier: GPL-3.0-or-later -->\n<!-- Generated by luch-linux/assets/gen_icon.py -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android" {AAPT if aapt else ""}\n'
            f'    android:width="{dp}dp" android:height="{dp}dp" android:viewportWidth="{vw}" android:viewportHeight="{vh}">\n')
    if group:
        body = (f'    <group android:scaleX="{SCALE}" android:scaleY="{SCALE}" android:translateX="{TX}" android:translateY="{TY_}">\n'
                f'        {body}\n    </group>')
    else:
        body = "    " + body
    return head + body + "\n</vector>\n"


def main():
    rays, dust = geometry()
    write("luch.svg", svg_colour(rays, dust))
    write("luch-symbolic.svg", SYMBOLIC)
    os.makedirs(os.path.join(HERE, "android"), exist_ok=True)
    write("android/ic_launcher_foreground.xml", android_foreground(rays, dust))
    write("android/ic_launcher_monochrome.xml", android_monochrome())
    write("android/ic_luch.xml", android_notification())
    try:
        import gi
        gi.require_version("GdkPixbuf", "2.0")
        from gi.repository import GdkPixbuf
        GdkPixbuf.Pixbuf.new_from_file_at_size(os.path.join(HERE, "luch.svg"), 512, 512).savev(
            os.path.join(HERE, "luch.png"), "png", [], [])
    except Exception as e:  # PNG is optional; the SVG is the source
        print("png skipped:", e)


def write(name, text):
    with open(os.path.join(HERE, name), "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
